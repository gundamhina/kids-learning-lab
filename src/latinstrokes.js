// 數字 0～9、大寫英文字母 A～Z 的筆順：自己畫的中心線（教育部的筆順資料只有注音）。
// 座標跟注音一樣是 2048×2048；每一筆是一串 [x, y, 筆寬]，照書寫方向排。沒有外框（d），strokeplay.js 會用粗線畫。
// 筆順照台灣小學常見教法：數字多半一筆寫完（4、5 兩筆）；字母先直後橫、由上往下、由左往右。

const PEN = 150
// 直線：從 (x1,y1) 到 (x2,y2)，切成幾段
function seg (x1, y1, x2, y2, n = 10) {
  return Array.from({ length: n + 1 }, (_, i) => [x1 + (x2 - x1) * i / n, y1 + (y2 - y1) * i / n])
}
// 弧線：圓心 (cx,cy)、半徑 rx、ry，角度從 a0 到 a1（度；0 是右邊、90 是下面，數字變大是順時針）
function arc (cx, cy, rx, ry, a0, a1, n = 28) {
  return Array.from({ length: n + 1 }, (_, i) => {
    const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180
    return [Math.round(cx + rx * Math.cos(a)), Math.round(cy + ry * Math.sin(a))]
  })
}
// 一筆：幾段接起來（重複的接點拿掉）
function stroke (...parts) {
  const pts = []
  for (const p of parts) for (const q of p) {
    const last = pts[pts.length - 1]
    if (!last || Math.hypot(last[0] - q[0], last[1] - q[1]) > 1) pts.push(q)
  }
  return { track: pts.map(([x, y]) => [Math.round(x), Math.round(y), PEN]) }
}

